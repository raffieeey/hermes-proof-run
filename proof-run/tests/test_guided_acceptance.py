"""Frozen acceptance contract for guided runs (docs/guided-runs.md).

Drives the plugin's registered surface, the /proof command and its hooks, through a
context that offers only the standard plugin API, with Hermes-shaped tool results
passed as JSON strings. Do not edit this file to make a build pass.
"""

from __future__ import annotations

import importlib.util
import json
import sys
import tempfile
import types
import unittest
from pathlib import Path

_PLUGIN_DIR = Path(__file__).resolve().parents[1]
_MODULE = "proof_run_plugin_under_test"
_ROOT: list = [None]


def _load_plugin():
    if _MODULE in sys.modules:
        return sys.modules[_MODULE]
    if "plugins" not in sys.modules:
        package = types.ModuleType("plugins")
        package.__path__ = []
        sys.modules["plugins"] = package
    storage = sys.modules.get("plugins.plugin_storage")
    if storage is None:
        storage = types.ModuleType("plugins.plugin_storage")
        sys.modules["plugins.plugin_storage"] = storage
    storage.plugin_data_dir = lambda _name: _ROOT[0]
    spec = importlib.util.spec_from_file_location(
        _MODULE,
        _PLUGIN_DIR / "__init__.py",
        submodule_search_locations=[str(_PLUGIN_DIR)],
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules[_MODULE] = module
    spec.loader.exec_module(module)
    return module


class StockHost:
    """A plugin context with only register_command and register_hook."""

    def __init__(self, root: Path):
        _ROOT[0] = root
        self.command = None
        self.hooks: dict = {}
        self.count = 0
        _load_plugin().register(self)

    def register_command(self, name, handler, **kwargs):
        self.command = handler

    def register_hook(self, name, callback, **kwargs):
        self.hooks[name] = callback

    def proof(self, text: str, session: str = "s1") -> str:
        return self.command(text, session_id=session)

    def call(self, tool: str, args: dict, result: dict, session: str = "s1"):
        """One tool call as the host runs it: pre hook, then the tool, then post hook."""
        self.count += 1
        call_id = f"call-{self.count}"
        verdict = self.hooks["pre_tool_call"](
            tool_name=tool, args=args, session_id=session, tool_call_id=call_id
        )
        if isinstance(verdict, dict) and verdict.get("action") == "block":
            return "blocked", str(verdict.get("message") or "")
        self.hooks["post_tool_call"](
            tool_name=tool,
            args=args,
            result=json.dumps(result),
            session_id=session,
            tool_call_id=call_id,
        )
        return "ran", ""

    def guide(self, session: str = "s1") -> str:
        hook = self.hooks.get("pre_llm_call")
        if hook is None:
            return ""
        out = hook(
            session_id=session,
            task_id="task",
            turn_id="turn",
            user_message="go",
            conversation_history=[],
            is_first_turn=False,
            model="follower",
            platform="cli",
            parent_session_id="",
            sender_id="",
        )
        if isinstance(out, dict):
            return str(out.get("context") or "")
        return out if isinstance(out, str) else ""


def term(output: str, code: int = 0) -> dict:
    return {"output": output, "exit_code": code, "error": None, "cwd": "/srv/app"}


def file_result(text: str) -> dict:
    return {"content": text, "total_lines": 1, "file_size": len(text), "truncated": False}


CFG = {"path": "/srv/app/config.yaml"}
HEALTH = {"service": "api"}


def deploy(version: str) -> dict:
    return {"command": f"./deploy.sh api {version}"}


class GuidedCase(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.host = StockHost(self.root)

    def ran(self, tool, args, result, session):
        state, message = self.host.call(tool, args, result, session)
        self.assertEqual(state, "ran", message)

    def blocked(self, tool, args, result, session) -> str:
        state, message = self.host.call(tool, args, result, session)
        self.assertEqual(state, "blocked")
        self.assertTrue(message.startswith("Proof Run:"), message)
        return message

    def teach_deploy(self, name: str = "deploy", save: str = "save version=2.1.0") -> str:
        h = self.host
        h.proof(f"start {name} ship the api", "teach")
        self.ran("read_file", CFG, file_result("replicas: 3"), "teach")
        self.ran("terminal", deploy("2.1.0"), term("deployed api 2.1.0 ok"), "teach")
        return h.proof(save, "teach")

    def teach_health(self, name: str) -> str:
        h = self.host
        h.proof(f"start {name}", "teach")
        self.ran("check_service_health", HEALTH, {"status": "healthy", "version": "2.0.9"}, "teach")
        self.ran("terminal", deploy("2.1.0"), term("ok"), "teach")
        return h.proof("save version=2.1.0", "teach")


class SaveTests(GuidedCase):
    def test_saved_procedure_gates_nothing_outside_a_run(self):
        reply = self.teach_deploy()
        self.assertIn("saved", reply.lower())
        self.assertIn("deploy", reply)
        self.assertIn("version", reply)
        self.assertNotIn("is live", reply)
        self.ran("terminal", {"command": "git status"}, term("clean"), "other")
        self.ran("terminal", {"command": "ls"}, term("a b"), "teach")
        self.assertEqual(self.host.guide("teach"), "")

    def test_strict_guard_from_stop_is_unchanged(self):
        h = self.host
        h.proof("start strict", "teach")
        self.ran("terminal", deploy("2.1.0"), term("ok"), "teach")
        reply = h.proof("stop", "teach")
        self.assertIn("is live", reply)
        state, message = h.call("terminal", {"command": "ls"}, term("x"), "other")
        self.assertEqual(state, "blocked")
        self.assertIn("demonstrated", message)

    def test_unknown_input_value_fails_and_keeps_the_recording(self):
        h = self.host
        h.proof("start deploy", "teach")
        self.ran("terminal", deploy("2.1.0"), term("ok"), "teach")
        bad = h.proof("save version=9.9.9", "teach")
        self.assertTrue(bad.startswith("Procedure not saved:"), bad)
        self.ran("terminal", {"command": "ls"}, term("x"), "other")
        good = h.proof("save version=2.1.0", "teach")
        self.assertIn("saved", good.lower())

    def test_procedure_survives_a_plugin_reload(self):
        self.teach_deploy()
        self.host = StockHost(self.root)
        self.assertIn("started", self.host.proof("run deploy version=2.2.0", "run").lower())
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")

    def test_inspect_and_status_describe_the_procedure(self):
        self.teach_deploy()
        text = self.host.proof("inspect deploy", "teach")
        for needle in ("terminal", "version", "2.1.0", "read_file.content"):
            self.assertIn(needle, text)
        self.assertIn("procedure", self.host.proof("status", "teach").lower())


class RunTests(GuidedCase):
    def test_new_input_is_guided_allowed_and_released(self):
        h = self.host
        self.teach_deploy()
        self.assertIn("started", h.proof("run deploy version=2.2.0", "run").lower())
        guide = h.guide("run")
        for needle in ("deploy", "terminal", "read_file", "./deploy.sh api 2.2.0", "version"):
            self.assertIn(needle, guide)
        self.assertIn("step 1 of 1", guide.lower())
        self.assertNotIn("./deploy.sh api 2.1.0", guide)
        self.assertEqual(h.guide("other"), "")
        status = h.proof("status", "run")
        self.assertIn("deploy", status)
        self.assertIn("step 1 of 1", status.lower())
        self.ran("terminal", deploy("2.2.0"), term("deployed api 2.2.0 ok"), "run")
        self.assertIn("completed", h.guide("run").lower())
        self.assertEqual(h.guide("run"), "")
        self.ran("terminal", {"command": "ls"}, term("a b"), "run")

    def test_off_procedure_use_of_a_step_tool_is_blocked_in_the_run_only(self):
        h = self.host
        self.teach_deploy()
        h.proof("run deploy version=2.2.0", "run")
        message = self.blocked("terminal", {"command": "rm -rf build"}, term(""), "run")
        self.assertIn("step 1 of 1", message.lower())
        self.assertIn("./deploy.sh api 2.2.0", message)
        self.blocked("terminal", deploy("2.1.0"), term("ok"), "run")
        self.ran("terminal", {"command": "ls"}, term("x"), "other")
        self.ran("write_file", {"path": "/tmp/n.txt", "content": "x"}, {"bytes_written": 1}, "run")
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")

    def test_steps_must_run_in_recorded_order_and_only_once(self):
        h = self.host
        h.proof("start release", "teach")
        self.ran("terminal", {"command": "./build.sh 2.1.0"}, term("built"), "teach")
        self.ran("terminal", deploy("2.1.0"), term("ok"), "teach")
        self.assertIn("saved", h.proof("save version=2.1.0", "teach").lower())
        h.proof("run release version=2.2.0", "run")
        self.assertIn("step 1 of 2", h.guide("run").lower())
        message = self.blocked("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("./build.sh 2.2.0", message)
        self.ran("terminal", {"command": "./build.sh 2.2.0"}, term("built"), "run")
        self.assertIn("step 2 of 2", h.guide("run").lower())
        self.blocked("terminal", {"command": "./build.sh 2.2.0"}, term("built"), "run")
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("completed", h.guide("run").lower())

    def test_unrelated_tool_between_read_and_action_is_harmless(self):
        h = self.host
        self.teach_deploy()
        self.assertIn("started", h.proof("run deploy version=2.2.0", "run").lower())
        self.ran("read_file", CFG, file_result("replicas: 5"), "run")
        self.ran("todo", {"todos": [{"id": "1", "content": "deploy"}]}, {"todos": 1}, "run")
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("completed", h.guide("run").lower())

    def test_volatile_results_never_break_or_poison_a_procedure(self):
        h = self.host
        h.proof("start deploy", "teach")
        self.ran("terminal", deploy("2.1.0"), term("deployed api 2.1.0 ok"), "teach")
        self.ran(
            "execute_code",
            {"code": "smoke_test('2.1.0')"},
            {"status": "success", "output": "ok", "exit_code": 0, "duration_seconds": 1.42},
            "teach",
        )
        self.assertIn("saved", h.proof("save version=2.1.0", "teach").lower())
        for version, session in (("2.2.0", "run-a"), ("2.3.0", "run-b")):
            self.assertIn("started", h.proof(f"run deploy version={version}", session).lower())
            self.ran(
                "terminal",
                deploy(version),
                term(f"deployed api {version} ok at 2026-11-14T10:02:11Z"),
                session,
            )
            self.ran(
                "execute_code",
                {"code": f"smoke_test('{version}')"},
                {"status": "success", "output": "ok", "exit_code": 0, "duration_seconds": 1.37},
                session,
            )
            self.assertIn("completed", h.guide(session).lower())
        self.assertNotIn("unproven", h.proof("status", "teach"))

    def test_failed_step_stops_and_holds_until_cancel(self):
        h = self.host
        self.teach_deploy()
        h.proof("run deploy version=2.2.0", "run")
        self.ran("terminal", deploy("2.2.0"), term("boom", code=1), "run")
        self.assertIn("stopped", h.guide("run").lower())
        self.assertIn("stopped", h.guide("run").lower())
        message = self.blocked("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("stopped", message.lower())
        self.assertIn("/proof cancel", message)
        self.ran("terminal", {"command": "ls"}, term("x"), "other")
        self.assertIn("cancelled", h.proof("cancel", "run").lower())
        self.assertEqual(h.guide("run"), "")
        self.ran("terminal", {"command": "ls"}, term("x"), "run")

    def test_five_blocked_attempts_stop_and_hold_the_run(self):
        h = self.host
        self.teach_deploy()
        h.proof("run deploy version=2.2.0", "run")
        for attempt in range(5):
            self.blocked("terminal", {"command": f"echo {attempt}"}, term("x"), "run")
        message = self.blocked("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("stopped", message.lower())
        self.assertIn("cancelled", h.proof("cancel", "run").lower())
        self.ran("terminal", {"command": "ls"}, term("x"), "run")

    def test_session_end_releases_the_run(self):
        h = self.host
        self.teach_deploy()
        self.assertIn("started", h.proof("run deploy version=2.2.0", "run").lower())
        self.blocked("terminal", {"command": "ls"}, term("x"), "run")
        h.hooks["on_session_finalize"](session_id="run")
        self.assertEqual(h.guide("run"), "")
        self.ran("terminal", {"command": "ls"}, term("x"), "run")

    def test_run_refuses_bad_inputs_recording_sessions_and_a_second_run(self):
        h = self.host
        self.teach_deploy()
        missing = h.proof("run deploy", "run")
        self.assertTrue(missing.startswith("Run not started:"), missing)
        self.assertIn("version", missing)
        extra = h.proof("run deploy version=2.2.0 region=eu", "run")
        self.assertTrue(extra.startswith("Run not started:"), extra)
        self.assertEqual(h.guide("run"), "")
        self.assertIn("started", h.proof("run deploy version=2.2.0", "run").lower())
        again = h.proof("run deploy version=2.3.0", "run")
        self.assertTrue(again.startswith("Run not started:"), again)
        self.assertIn("./deploy.sh api 2.2.0", h.guide("run"))
        h.proof("start other", "rec")
        busy = h.proof("run deploy version=2.2.0", "rec")
        self.assertTrue(busy.startswith("Run not started:"), busy)


class InputTests(GuidedCase):
    def test_numeric_inputs_keep_their_json_type(self):
        h = self.host
        h.proof("start reserve", "teach")
        self.ran(
            "reserve_stock",
            {"sku": "A1", "qty": 5},
            {"reserved": True, "reservation_id": "R-1"},
            "teach",
        )
        self.assertIn("saved", h.proof("save sku=A1 qty=5", "teach").lower())
        wrong = h.proof("run reserve sku=B2 qty=many", "run")
        self.assertTrue(wrong.startswith("Run not started:"), wrong)
        self.assertIn("started", h.proof("run reserve sku=B2 qty=7", "run").lower())
        self.blocked("reserve_stock", {"sku": "B2", "qty": "7"}, {"reserved": True}, "run")
        self.ran("reserve_stock", {"sku": "B2", "qty": 7}, {"reserved": True}, "run")

    def test_quoted_values_and_literal_braces(self):
        h = self.host
        recorded = "docker ps --format '{{.Names}}' && git commit -m \"fix bug\""
        h.proof("start commit", "teach")
        self.ran("terminal", {"command": recorded}, term("ok"), "teach")
        self.assertIn("saved", h.proof('save msg="fix bug"', "teach").lower())
        self.assertIn("started", h.proof('run commit msg="ship it now"', "run").lower())
        expected = "docker ps --format '{{.Names}}' && git commit -m \"ship it now\""
        self.assertIn("ship it now", h.guide("run"))
        self.ran("terminal", {"command": expected}, term("ok"), "run")


class PinTests(GuidedCase):
    def test_unpinned_read_fact_does_not_block(self):
        h = self.host
        self.teach_health("plain")
        self.assertIn("started", h.proof("run plain version=2.2.0", "run").lower())
        self.ran("check_service_health", HEALTH, {"status": "degraded", "version": "2.0.9"}, "run")
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("completed", h.guide("run").lower())

    def test_pinned_fact_needs_a_fresh_matching_read(self):
        h = self.host
        self.teach_health("guarded")
        bad = h.proof("pin guarded check_service_health.nope", "teach")
        self.assertTrue(bad.startswith("Not pinned:"), bad)
        self.assertIn("pinned", h.proof("pin guarded check_service_health.status", "teach").lower())
        self.assertIn("[pinned]", h.proof("inspect guarded", "teach"))
        h.proof("run guarded version=2.2.0", "run")
        self.assertIn("check_service_health", h.guide("run"))
        message = self.blocked("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("check_service_health.status", message)
        self.ran("check_service_health", HEALTH, {"status": "degraded", "version": "2.0.9"}, "run")
        message = self.blocked("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("check_service_health.status", message)
        self.assertIn("degraded", message)
        self.ran("check_service_health", HEALTH, {"status": "healthy", "version": "2.1.0"}, "run")
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")
        self.assertIn("completed", h.guide("run").lower())

    def test_unpin_removes_the_precondition(self):
        h = self.host
        self.teach_health("guarded")
        h.proof("pin guarded check_service_health.status", "teach")
        h.proof("unpin guarded check_service_health.status", "teach")
        self.assertNotIn("[pinned]", h.proof("inspect guarded", "teach"))
        h.proof("run guarded version=2.2.0", "run")
        self.ran("terminal", deploy("2.2.0"), term("ok"), "run")


